import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const monsterDir = join(root, "public", "monsters");
const outputFile = join(root, "lib", "companyMonsterAssets.ts");
const assetPattern = /^([0-9A-Z]+)-(.+)\.png$/u;

const files = readdirSync(monsterDir)
  .map((file) => file.normalize("NFC"))
  .sort((a, b) => a.localeCompare(b, "ja"));

const ignoredFiles = [];
const parsedAssets = [];

for (const file of files) {
  const match = file.match(assetPattern);
  if (!match) {
    ignoredFiles.push(file);
    continue;
  }

  parsedAssets.push({
    ticker: match[1],
    company: match[2],
    file
  });
}

const duplicateTickerMap = new Map();

for (const asset of parsedAssets) {
  const group = duplicateTickerMap.get(asset.ticker) ?? [];
  group.push(asset.file);
  duplicateTickerMap.set(asset.ticker, group);
}

const duplicateTickers = [...duplicateTickerMap.entries()]
  .filter(([, group]) => group.length > 1)
  .map(([ticker, files]) => ({ ticker, files }));

const assets = parsedAssets
  .sort((a, b) => a.ticker.localeCompare(b.ticker, "ja"));

const diagnostics = {
  totalFiles: files.length,
  usableFiles: assets.length,
  ignoredFiles,
  duplicateTickers
};

const source = `// This file is generated by scripts/sync-monster-assets.mjs.
// Add monster images as public/monsters/<code>-<company>.png, then run npm run sync:monsters.

export type CompanyMonsterAsset = {
  ticker: string;
  company: string;
  file: string;
};

export const companyMonsterAssets = ${JSON.stringify(assets, null, 2)} satisfies CompanyMonsterAsset[];

export const companyMonsterAssetDiagnostics = ${JSON.stringify(diagnostics, null, 2)} as const;
`;

writeFileSync(outputFile, source);
console.log(`Synced ${assets.length} company monster assets from ${files.length} files.`);
if (ignoredFiles.length > 0) {
  console.log(`Ignored ${ignoredFiles.length} non-company files.`);
}
if (duplicateTickers.length > 0) {
  console.warn("Duplicate ticker assets detected:");
  for (const duplicate of duplicateTickers) {
    console.warn(`- ${duplicate.ticker}: ${duplicate.files.join(", ")}`);
  }
}
